"""Plain factory functions that build valid, unsaved model instances.

Why not polyfactory? Our tables carry CHECK constraints (13-digit barcode, "moderate or
high needs a source", two-letter locale ...). Randomly generated values violate them
constantly, so we'd override nearly every field anyway. Explicit defaults + keyword
overrides are shorter and always valid.

Usage:  session.add(make_product(name="Cream", score=80))
"""

import itertools
from typing import Any

from app.core.enums import RiskLevel
from app.modules.catalog.enums import ProductSource
from app.modules.catalog.models import Brand, Category, CategoryTranslation, Product
from app.modules.ingredients import normalize
from app.modules.ingredients.models import Ingredient, IngredientAlias, IngredientTranslation

_sequence = itertools.count(1)


def make_barcode() -> str:
    """A unique, VALID GTIN-13 (correct check digit), with the Tunisian prefix 619.

    The check digit is computed here independently of the production code, so a bug in
    `normalize_gtin` cannot hide behind test data generated by the same bug.
    """
    body = f"619{next(_sequence):09d}"  # 12 digits
    weighted = sum(int(digit) * (1 if index % 2 == 0 else 3) for index, digit in enumerate(body))
    return body + str((10 - weighted % 10) % 10)


def make_brand(**overrides: Any) -> Brand:
    n = next(_sequence)
    return Brand(**{"name": f"Brand {n}", **overrides})


def make_category(names: dict[str, str] | None = None, **overrides: Any) -> Category:
    """`names` maps locale -> display name, e.g. {"en": "Moisturizer", "fr": "Hydratant"}."""
    n = next(_sequence)
    category = Category(**{"slug": f"category-{n}", **overrides})
    category.translations = [
        CategoryTranslation(locale=locale, name=name) for locale, name in (names or {}).items()
    ]
    return category


def make_ingredient(
    aliases: list[str] | None = None,
    rationale: dict[str, str] | None = None,
    **overrides: Any,
) -> Ingredient:
    """An ingredient that already satisfies the dictionary invariant: it has an alias for its
    own INCI name, plus any extra names in `aliases`. `rationale` maps locale -> text."""
    n = next(_sequence)
    values: dict[str, Any] = {"inci_name": f"INGREDIENT {n}", "risk_level": RiskLevel.LOW}
    values.update(overrides)
    if values["risk_level"] in (RiskLevel.MODERATE, RiskLevel.HIGH):
        values.setdefault("source_ref", "test-source")  # required by a DB constraint
    ingredient = Ingredient(**values)

    names = [values["inci_name"], *(aliases or [])]
    ingredient.aliases = [
        IngredientAlias(alias=name, normalized_alias=normalize(name)) for name in names
    ]
    ingredient.translations = [
        IngredientTranslation(locale=locale, rationale=text)
        for locale, text in (rationale or {}).items()
    ]
    return ingredient


def make_product(**overrides: Any) -> Product:
    n = next(_sequence)
    values: dict[str, Any] = {
        "barcode": make_barcode(),
        "name": f"Product {n}",
        "source": ProductSource.MANUAL,
    }
    values.update(overrides)
    return Product(**values)
